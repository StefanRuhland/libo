char	*strrchr(const char *s, int c)
{
	int	i;

	i = 0;
	while (s[i] != '\0')
		i++;
	while (s[i] != c && i > 0)
		i--;
	if (s[i] == c)
		return (&s[i]);
	else
		return (NULL);
}
